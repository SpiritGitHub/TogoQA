def seed_sources():
    engine = create_engine(DATABASE_URL)
    with engine.begin() as conn:
        existing = conn.execute(text("SELECT COUNT(*) FROM sources")).scalar()
        if existing > 0:
            print(f"Table sources contient déjà {existing} enregistrements. Seed ignoré.")
            return

        for s in SOURCES:
            conn.execute(
                text("""
                    INSERT INTO sources (name, base_url, authority_tier, authority_score,
                        category, source_owner, thematic_scope, update_frequency,
                        corroboration_required)
                    VALUES (:name, :base_url, :authority_tier, :authority_score,
                        :category, :source_owner, :thematic_scope, :update_frequency,
                        :corroboration_required)
                """),
                s,
            )
        print(f"{len(SOURCES)} sources insérées avec succès.")


if __name__ == "__main__":
    seed_sources()
